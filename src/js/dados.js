// Versão dos dados (aumentar ao alterar produtosIniciais)
const VERSAO_DADOS = 2;
(function migrarProdutos() {
  let salvos = null;
  try { salvos = JSON.parse(localStorage.getItem("techstore_produtos")); } catch (e) {}
  const atual = localStorage.getItem("techstore_versao") == VERSAO_DADOS;
  localStorage.setItem("techstore_versao", VERSAO_DADOS);
  if (!salvos || atual) return;
  const ids = new Set(produtosIniciais.map((p) => p.id));
  const lista = [...produtosIniciais, ...salvos.filter((p) => !ids.has(p.id))];
  localStorage.setItem("techstore_produtos", JSON.stringify(lista));
})();
